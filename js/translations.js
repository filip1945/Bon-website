function changeLanguage(lang) {
    const selectedLanguage = translations[lang] ? lang : "mk";

    localStorage.setItem("bonLanguage", selectedLanguage);
    document.documentElement.lang = selectedLanguage;

    document.querySelectorAll("[data-i18n]").forEach(element => {
        const key = element.getAttribute("data-i18n");
        const translation = translations[selectedLanguage][key];

        if (translation !== undefined) {
            element.textContent = translation;
        }
    });

    document.querySelectorAll("[data-i18n-html]").forEach(element => {
        const key = element.getAttribute("data-i18n-html");
        const translation = translations[selectedLanguage][key];

        if (translation !== undefined) {
            element.innerHTML = translation;
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
        const key = element.getAttribute("data-i18n-placeholder");
        const translation = translations[selectedLanguage][key];

        if (translation !== undefined) {
            element.placeholder = translation;
        }
    });

    const hamburger = document.getElementById("hamburger");

    if (hamburger && translations[selectedLanguage].contactHamburger) {
        hamburger.setAttribute(
            "aria-label",
            translations[selectedLanguage].contactHamburger
        );
    }

    document.querySelectorAll(".lang-btn").forEach(button => {
        button.classList.toggle(
            "active",
            button.dataset.lang === selectedLanguage
        );
    });

    if (document.querySelector(".product-details")) {
        document.title = selectedLanguage === "mk"
            ? "Детали за производ - BON"
            : "Product Details - BON";

    } else if (document.querySelector(".category-hero")) {
        document.title = selectedLanguage === "mk"
            ? "Производи - BON"
            : "Products - BON";

    } else if (document.querySelector(".products-hero")) {
        document.title = selectedLanguage === "mk"
            ? "Производи - BON"
            : "Products - BON";

    } else if (document.querySelector("#kontakt")) {
        document.title = selectedLanguage === "mk"
            ? "Контакт - BON"
            : "Contact - BON";

    } else if (document.querySelector("#hero")) {
        document.title = selectedLanguage === "mk"
            ? "За нас - BON"
            : "About Us - BON";

    } else if (document.querySelector("#gorno")) {
        document.title = selectedLanguage === "mk"
            ? "BON - Почетна"
            : "BON - Home";
    }

    document.dispatchEvent(new CustomEvent("languageChanged", {
        detail: { language: selectedLanguage }
    }));
}


document.addEventListener("DOMContentLoaded", () => {
    document.querySelectorAll(".lang-btn").forEach(button => {
        button.addEventListener("click", () => {
            changeLanguage(button.dataset.lang);
        });
    });

    const savedLanguage = localStorage.getItem("bonLanguage") || "mk";
    changeLanguage(savedLanguage);
});
